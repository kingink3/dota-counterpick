// Build src/clock-glyphs.ts (digit templates) from the real clock captures in
// test/fixtures/clock.json, with the same segmentation + resampling the reader uses.
//     npx tsx scripts/build-clock-glyphs.ts
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { GLYPH_H, GLYPH_W, glyphVector, segments } from "../src/clock-match.js";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const fx = JSON.parse(readFileSync(join(ROOT, "test", "fixtures", "clock.json"), "utf8")) as {
  frames: Array<{ text: string; w: number; h: number; rgba: string }>;
};
const acc = new Map<string, Float32Array[]>();
for (const f of fx.frames) {
  const px = new Uint8ClampedArray(Buffer.from(f.rgba, "base64"));
  const { segs, lum } = segments(px, f.w, f.h);
  if (segs.length !== f.text.length) throw new Error(`${f.text}: ${segs.length} segments`);
  segs.forEach((s, i) => {
    const c = f.text[i]!;
    if (c === ":") return;
    acc.set(c, [...(acc.get(c) ?? []), glyphVector(lum, f.w, s.x0, s.y0, s.x1 - s.x0, s.y1 - s.y0)]);
  });
}
const out: Record<string, number[]> = {};
for (const [d, vs] of [...acc].sort()) {
  const m = new Float32Array(GLYPH_W * GLYPH_H);
  for (const v of vs) for (let i = 0; i < m.length; i++) m[i] = m[i]! + v[i]!;
  const n = Math.sqrt(m.reduce((s, x) => s + x * x, 0)) || 1;
  out[d] = Array.from(m, (x) => Math.round((x / n) * 1e4) / 1e4);
}
if (Object.keys(out).length !== 10) throw new Error(`only digits ${Object.keys(out).join("")}`);
writeFileSync(
  join(ROOT, "src", "clock-glyphs.ts"),
  "// GENERATED by scripts/build-clock-glyphs.ts from test/fixtures/clock.json - do not edit.\n" +
    "// Dota 2 top-bar clock digits, 8x12 normalised luminance.\n" +
    `export const GLYPHS: Record<string, number[]> = ${JSON.stringify(out)};\n`,
);
console.log(`clock glyphs: ${Object.keys(out).join("")} from ${fx.frames.length} captures`);
